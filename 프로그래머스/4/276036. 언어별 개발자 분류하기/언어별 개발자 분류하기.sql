WITH SKILL AS (
    SELECT
        SUM(CASE WHEN NAME = 'Python' THEN CODE ELSE 0 END) AS PYTHON,
        SUM(CASE WHEN NAME = 'C#' THEN CODE ELSE 0 END) AS CSHARP,
        SUM(CASE WHEN CATEGORY = 'Front End' THEN CODE ELSE 0 END) AS FRONT_END
    FROM SKILLCODES
)
SELECT *
FROM (
    SELECT
        CASE
            WHEN (SKILL_CODE & SKILL.FRONT_END) > 0
             AND (SKILL_CODE & SKILL.PYTHON) > 0 THEN 'A'
            WHEN (SKILL_CODE & SKILL.CSHARP) > 0 THEN 'B'
            WHEN (SKILL_CODE & SKILL.FRONT_END) > 0 THEN 'C'
        END AS GRADE,
        ID,
        EMAIL
    FROM DEVELOPERS
    CROSS JOIN SKILL
) AS RESULT
WHERE GRADE IS NOT NULL
ORDER BY GRADE, ID;